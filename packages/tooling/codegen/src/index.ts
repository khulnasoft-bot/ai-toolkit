import { createAgent, type AgentConfig } from '@ai-toolkit/agents';
import { createToolRegistry, type Tool } from '@ai-toolkit/tools';

export type CodegenConfig = {
  readonly template: string;
  readonly language: string;
  readonly outputDir: string;
};

export interface CodeGenerator {
  generate(config: CodegenConfig): Promise<string>;
}

export interface CodegenEngine {
  registerGenerator(name: string, generator: CodeGenerator): void;
  getGenerator(name: string): CodeGenerator | undefined;
}

export function createCodegenEngine(): CodegenEngine {
  const generators = new Map<string, CodeGenerator>();

  return {
    registerGenerator: (name, generator) => generators.set(name, generator),
    getGenerator: name => generators.get(name),
  };
}

function agentTemplate(name: string, modelId: string): string {
  return `import { createAgent } from '@ai-toolkit/agents';

export const ${name} = createAgent({
  modelId: '${modelId}',
  name: '${name}',
  description: 'Generated agent scaffold.',
  instructions: 'You are a helpful assistant generated by AI Toolkit codegen.',
  maxSteps: 5,
});
`;
}

function toolTemplate(name: string): string {
  return `import { type Tool } from '@ai-toolkit/tools';

export const ${name}Tool: Tool = {
  name: '${name}',
  description: 'Generated tool scaffold.',
  parameters: {
    type: 'object',
    properties: {},
    required: [],
  },
  execute: async () => {
    return { success: true, output: '${name} executed' };
  },
};
`;
}

class AgentGenerator implements CodeGenerator {
  async generate(config: CodegenConfig): Promise<string> {
    const name = config.template || 'MyAgent';
    const modelId = 'openai/gpt-4o';

    const agentCode = agentTemplate(name, modelId);

    const tools = createToolRegistry();
    const echoTool: Tool = {
      name: 'echo',
      description: 'Echo tool scaffold.',
      parameters: { type: 'object', properties: {}, required: [] },
      execute: async () => 'echo',
    };
    tools.registerTool(echoTool);

    const configObj: AgentConfig = {
      modelId,
      name,
      description: 'Generated agent scaffold.',
      instructions: 'You are a helpful assistant.',
    };
    const agent = createAgent(configObj);

    const toolFiles = tools.listTools().map(tool => toolTemplate(tool.name));

    return [
      `// Generated by @ai-toolkit/codegen`,
      `// Template: ${config.template}`,
      `// Language: ${config.language}`,
      `// Output dir: ${config.outputDir}`,
      '',
      agentCode,
      '',
      ...toolFiles,
      '',
      `// Agent instance created with ${tools.listTools().length} tool(s) registered.`,
      `const agent = ${name};`,
    ].join('\n');
  }
}

export function createAgentGenerator(): CodeGenerator {
  return new AgentGenerator();
}
